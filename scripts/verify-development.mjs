import { rolldown } from 'rolldown';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const bundle = await rolldown({ input: 'scripts/library-test-entry.mjs', platform: 'node', external: [/^node:/] });
await bundle.write({ file: '.verification/development-test.mjs', format: 'esm' }); await bundle.close();
const { initialProject, captureCheckpoint, restoreCheckpoint, appendMechanism, compareProjects, nextCanId, parseHistory, historyFile, mergeHistory, HISTORY_LIMIT, newDevice, validate, assembleProject, listCheckpoints, saveCheckpoint } = await import('../.verification/development-test.mjs');
const base = { ...structuredClone(initialProject), team: 9999, checks: { mechanical: true, direction: true } };
const original = JSON.stringify(base);
const start = captureCheckpoint(base, 'Drive + intake working', 'Directions verified; shooter not tuned.');
assert.equal(JSON.stringify(base), original, 'capturing a version cannot mutate the active design');
assert.deepEqual(compareProjects(start.project, base), [], 'resolved library metadata does not create a false change');
assert.ok(start.project.libraries.lock.vendors.rev.manifest.version);
const added = appendMechanism(base, { name: 'Feeder', controller: 'SparkFlex', can: nextCanId(base) });
assert.equal(JSON.stringify(base), original, 'addition is immutable');
assert.deepEqual(added.motors.slice(0, base.motors.length), base.motors);
assert.deepEqual(added.commands.slice(0, base.commands.length), base.commands);
assert.deepEqual(added.bindings, base.bindings);
assert.deepEqual(added.auto, base.auto);
assert.deepEqual(added.checks, {}, 'hardware additions require renewed checks');
assert.equal(added.commands.at(-1).subsystem, added.subsystems.at(-1).id);
assert.equal(added.motors.at(-1).subsystem, added.subsystems.at(-1).id);
assert.equal(added.commands.at(-1).output, .2);
assert.equal(added.commands.at(-1).timeout, 1);
assert.equal(new Set(added.motors.map(m => m.id)).size, added.motors.length);
assert.deepEqual(validate(added).filter(x => x.level === 'error'), []);
const additions = compareProjects(start.project, added);
assert.equal(additions.filter(c => c.kind === 'added').length, 3);
const second = captureCheckpoint(added, 'Feeder installed');
added.commands.at(-1).output = .35;
added.motors.at(-1).can = 9;
added.routines = [{ id: 'feedAndShoot', name: 'Feed and shoot', timeout: 4, steps: [{ id: 'together', type: 'parallel', commands: [added.commands.at(-1).id, 'shoot'] }] }];
const changed = compareProjects(second.project, added);
assert.ok(changed.some(c => c.details.includes('Output: 0.2 → 0.35')));
assert.ok(changed.some(c => c.details.includes('CAN ID / PWM: 7 → 9')));
assert.ok(changed.some(c => c.name === 'Feed and shoot' && c.kind === 'added'));
assert.equal(second.project.commands.at(-1).output, .2, 'later changes cannot mutate a checkpoint');
const restored = restoreCheckpoint(start);
assert.deepEqual(restored.motors, base.motors);
assert.deepEqual(restored.commands, base.commands);
assert.equal(restored.libraries.mode, 'frozen');
assert.deepEqual(restored.libraries.lock, start.project.libraries.lock);
assert.deepEqual(restored.checks, {});
assert.deepEqual(start.project.checks, base.checks, 'restore cannot alter checkpoint evidence');
const third = captureCheckpoint(added, 'Feeder + shooter routine');
assert.deepEqual(parseHistory(historyFile([third, second, start])), [third, second, start]);
assert.equal(mergeHistory([start], [start, second]).length, 2, 'history import is idempotent');
assert.throws(() => mergeHistory([start], [{ ...start, notes: 'conflicting content' }]), /conflicts/);
assert.throws(() => parseHistory(historyFile([start, start])), /duplicate/);
assert.throws(() => mergeHistory(Array.from({ length: HISTORY_LIMIT }, (_, i) => ({ ...start, id: 'checkpoint_' + i })), [second]), /limit|Keep up to/);
assert.throws(() => appendMechanism(base, { name: 'Intake', controller: 'none', can: -1 }), /different name/);
assert.throws(() => appendMechanism(base, { name: 'Feeder', controller: 'SparkMax', can: 1 }), /already assigned/);
const ports = { ...base, devices: [{ ...newDevice('canrange', 'range', 'intake'), address: 7 }] };
assert.equal(nextCanId(ports), 8, 'automatic CAN address accounts for sensors');
const shell = appendMechanism(base, { name: 'Climber planning', controller: 'none', can: -1 });
assert.equal(shell.motors.length, base.motors.length);
assert.equal(shell.commands.length, base.commands.length);
assert.deepEqual(validate(shell).filter(x => x.level === 'error'), []);
assert.deepEqual(compareProjects(base, { ...base, checks: {} }), [], 'commissioning checklist state is not a design edit');
const remapped = structuredClone(base); remapped.bindings[0].command = 'shoot';
assert.ok(compareProjects(base, remapped).some(c => c.details.includes('Action: Collect → Shoot')), 'reference changes use readable names');
await assert.rejects(() => listCheckpoints(), /storage is unavailable/, 'unavailable browser storage is reported');
await assert.rejects(() => saveCheckpoint(start), /storage is unavailable/, 'a failed write cannot report a saved checkpoint');
for (const language of ['Java', 'C++', 'Python']) {
  const files = await assembleProject({ ...added, language }, async path => new Uint8Array(await fs.readFile('public' + path)));
  assert.ok(files['LOGIC.md'].includes('Feed and shoot'));
  const recovered = await assembleProject({ ...restored, language }, async path => new Uint8Array(await fs.readFile('public' + path)));
  assert.ok(!recovered['LOGIC.md'].includes('Feed and shoot'));
}
await fs.mkdir('.verification/development', { recursive: true });
await fs.writeFile('.verification/development/project-import.json', JSON.stringify(added, null, 2));
await fs.writeFile('.verification/development/history-import.json', historyFile([start, second, third]));
console.log('PASS: immutable checkpoints, iterative additions, preserved IDs/assignments, real change summaries, restore with pinned libraries, history roundtrip/conflict limits, CAN allocation, and exports before/after development in all languages.');
